// Content-hash the hero video into /public/media and emit a manifest.
//
// WHY: We want to cache the hero clip `immutable` (download once, reuse across
// visits) WITHOUT ever stranding a returning visitor on a stale file. The safe
// way to do that is a content-hashed filename: when the video's bytes change, the
// hash changes, the URL changes, and old caches are bypassed automatically.
//
// The bundler (Turbopack) won't emit .mp4 imports, so we do it here. Source of
// truth is src/assets/hero-video.mp4 (committed); the hashed copy in
// /public/media and the manifest are generated build artifacts (gitignored).
// Runs on `prebuild` and `predev`.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync, readdirSync, rmSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const SRC = join(root, 'src', 'assets', 'hero-video.mp4');
const OUT_DIR = join(root, 'public', 'media');
const GEN_DIR = join(root, 'src', 'generated');

const bytes = readFileSync(SRC);
const hash = createHash('sha256').update(bytes).digest('hex').slice(0, 12);
const filename = `hero-video.${hash}.mp4`;

mkdirSync(OUT_DIR, { recursive: true });
for (const f of readdirSync(OUT_DIR)) {
  if (/^hero-video\.[a-f0-9]+\.mp4$/.test(f) && f !== filename) rmSync(join(OUT_DIR, f));
}
writeFileSync(join(OUT_DIR, filename), bytes);

mkdirSync(GEN_DIR, { recursive: true });
writeFileSync(
  join(GEN_DIR, 'hero-asset.ts'),
  `// AUTO-GENERATED by scripts/prepare-hero-video.mjs — do not edit by hand.\n` +
    `// Content-hashed URL; safe to cache immutably (see next.config.ts).\n` +
    `export const HERO_VIDEO = '/media/${filename}';\n`,
);

console.log(`[hero] ${filename} (${(bytes.length / 1e6).toFixed(2)} MB)`);
